import pg from 'pg';
const c = new pg.Client({ connectionString: process.env.HELMION_DATABASE_URL });
await c.connect();
const cols = await c.query(`select column_name from information_schema.columns where table_schema='helmion' and table_name='profile_sync_jobs' order by ordinal_position`);
console.log('JOB COLS:', cols.rows.map(r=>r.column_name).join(','));
const jobs = await c.query(`select * from helmion.profile_sync_jobs order by created_at`);
for (const j of jobs.rows) console.log('JOB:', JSON.stringify(j).slice(0, 400));
const link = await c.query(`select last_used_at from helmion.desktop_links where id='637b8061-4f09-4365-8dae-fca3e592fb6a'`);
console.log('NEW LINK last_used_at:', JSON.stringify(link.rows));
await c.end();
