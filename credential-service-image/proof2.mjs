import pg from 'pg';
const c = new pg.Client({ connectionString: process.env.HELMION_DATABASE_URL });
await c.connect();
const jobs = await c.query(`select id, status, created_at from helmion.profile_sync_jobs order by created_at`);
console.log('JOBS:', JSON.stringify(jobs.rows));
const rpt = await c.query(`select job_id, ok, files_written, created_at from helmion.profile_sync_reports order by created_at desc limit 4`);
console.log('REPORTS:', JSON.stringify(rpt.rows));
const link = await c.query(`select id, tenant_id, linked_at, last_used_at from helmion.desktop_links where id='637b8061-4f09-4365-8dae-fca3e592fb6a'`);
console.log('NEW LINK:', JSON.stringify(link.rows));
await c.end();
